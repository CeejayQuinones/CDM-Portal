<?php

namespace App\Services\Event;

use App\Models\Event;
use App\Models\EventAttendance;
use App\Models\Student;
use App\Models\User;
use Dompdf\Dompdf;
use Dompdf\Options;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Pagination\LengthAwarePaginator;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpFoundation\StreamedResponse;

class EventReportService
{
    public function __construct(private readonly EventAudienceResolver $audiences, private readonly EventAuditWriter $audit) {}

    public function index(array $filters, User $user): LengthAwarePaginator
    {
        $query = $this->audiences->visibleTo(Event::query(), $user)
            ->with(['audiences.course:id,course_code', 'audiences.section:id,section_name', 'parent.audiences.course:id,course_code', 'parent.audiences.section:id,section_name']);
        $query->when($filters['search'] ?? null, fn (Builder $q, $value) => $q->where(fn (Builder $event) => $event->where('title', 'like', "%$value%")->orWhere('venue', 'like', "%$value%")))
            ->when($filters['status'] ?? null, fn (Builder $q, $value) => $q->where('status', $value))
            ->when($filters['from'] ?? null, fn (Builder $q, $value) => $q->whereDate('ends_at', '>=', $value))
            ->when($filters['to'] ?? null, fn (Builder $q, $value) => $q->whereDate('starts_at', '<=', $value))
            ->when($filters['audience'] ?? null, function (Builder $q, $value): void {
                $q->where(fn (Builder $event) => $event->whereHas('audiences', fn (Builder $audience) => $audience->where('audience_type', $value))
                    ->orWhere(fn (Builder $inherited) => $inherited->whereDoesntHave('audiences')->whereHas('parent.audiences', fn (Builder $audience) => $audience->where('audience_type', $value))));
            });
        $page = $query->orderByDesc('starts_at')->paginate($filters['per_page'] ?? 25);
        $page->getCollection()->transform(fn (Event $event) => $this->eventSummary($event));

        return $page;
    }

    public function report(Event $event, array $filters, User $actor, bool $audit = true): array
    {
        $event->loadMissing(['audiences.course:id,course_code', 'audiences.section:id,section_name', 'parent.audiences.course:id,course_code', 'parent.audiences.section:id,section_name']);
        $students = $this->studentQuery($event, $filters);
        $page = $students->paginate($filters['per_page'] ?? 50);
        $ids = $page->getCollection()->pluck('id');
        $attendance = EventAttendance::query()->where('event_id', $event->id)->whereIn('student_id', $ids)
            ->with(['courseAtAttendance:id,course_code', 'sectionAtAttendance:id,section_name,year_level', 'recorder.profile'])->get()->keyBy('student_id');
        $page->getCollection()->transform(fn (Student $student) => $this->row($student, $attendance->get($student->id)));
        if ($audit) {
            DB::transaction(fn () => $this->audit->write($event, $actor, 'report.generated', ['filters' => $this->safeFilters($filters)]));
        }

        return [
            'event' => $this->eventInformation($event),
            'summary' => $this->summary($event),
            'breakdowns' => $this->breakdowns($event),
            'sub_events' => $this->subEventSummary($event),
            'students' => $page,
        ];
    }

    public function csv(Event $event, array $filters, User $actor): StreamedResponse
    {
        DB::transaction(fn () => $this->audit->write($event, $actor, 'report.exported', ['format' => 'csv', 'filters' => $this->safeFilters($filters)]));
        $filename = Str::slug($event->title).'-attendance-'.$event->starts_at->format('Y-m-d').'.csv';
        $summary = $this->summary($event);
        $information = $this->eventInformation($event);

        return response()->streamDownload(function () use ($event, $filters, $actor, $summary, $information): void {
            $out = fopen('php://output', 'w');
            fputcsv($out, ['Colegio de Montalban']);
            fputcsv($out, ['Event Attendance Report']);
            fputcsv($out, ['Event', $this->safeCell($information['title'])]);
            fputcsv($out, ['Schedule', $information['starts_at'].' - '.$information['ends_at']]);
            fputcsv($out, ['Venue', $this->safeCell($information['venue'])]);
            fputcsv($out, ['Audience', $this->safeCell($information['audience'])]);
            fputcsv($out, ['Generated at', now()->toIso8601String()]);
            fputcsv($out, ['Generated by', $this->safeCell(trim(($actor->profile?->first_name ?? '').' '.($actor->profile?->last_name ?? '')) ?: $actor->username)]);
            fputcsv($out, []);
            fputcsv($out, ['Eligible', $summary['eligible'], 'Checked In', $summary['checked_in'], 'Checked Out', $summary['checked_out'], 'Completed', $summary['completed'], 'In Progress', $summary['in_progress'], 'Incomplete', $summary['incomplete']]);
            fputcsv($out, ['Late', $summary['late'], 'Absent', $summary['absent'], 'Absence Finalized', $summary['absence_finalized'] ? 'Yes' : 'No', 'Attendance Rate', $summary['attendance_rate'].'%', 'Completion Rate', $summary['completion_rate'].'%', 'Average Minutes', $summary['average_participation_minutes'] ?? '—']);
            fputcsv($out, []);
            fputcsv($out, ['Student Number', 'Student Name', 'Course', 'Year', 'Section', 'Check-in Time', 'Check-out Time', 'Participation Minutes', 'Completion', 'Status', 'Check-in Method', 'Check-out Method', 'Recorded / Corrected By']);
            $query = $this->studentQuery($event, $filters);
            $query->chunkById(500, function ($students) use ($event, $out): void {
                $records = EventAttendance::query()->where('event_id', $event->id)->whereIn('student_id', $students->pluck('id'))
                    ->with(['courseAtAttendance:id,course_code', 'sectionAtAttendance:id,section_name,year_level', 'recorder.profile'])->get()->keyBy('student_id');
                foreach ($students as $student) {
                    $row = $this->row($student, $records->get($student->id));
                    fputcsv($out, array_map($this->safeCell(...), $this->exportColumns($row)));
                }
            }, 'students.id', 'id');
            fclose($out);
        }, $filename, ['Content-Type' => 'text/csv; charset=UTF-8', 'Cache-Control' => 'private, no-store']);
    }

    public function xlsx(Event $event, array $filters, User $actor): StreamedResponse
    {
        DB::transaction(fn () => $this->audit->write($event, $actor, 'report.exported', ['format' => 'xlsx', 'filters' => $this->safeFilters($filters)]));
        $context = $this->exportContext($event);

        return response()->streamDownload(function () use ($event, $filters, $context): void {
            $book = new Spreadsheet;
            $overview = $book->getActiveSheet();
            $overview->setTitle('Overview');
            $overview->fromArray([
                ['Colegio de Montalban'], ['Event Attendance Report'], ['Event', $this->safeCell($context['event']['title'])],
                ['Schedule', $context['event']['starts_at'].' - '.$context['event']['ends_at']], ['Venue', $this->safeCell($context['event']['venue'])],
                [], ['Metric', 'Value'], ...collect($context['summary'])->map(fn ($value, $key) => [$key, is_bool($value) ? ($value ? 'Yes' : 'No') : $value])->values()->all(),
            ]);
            $sheet = $book->createSheet()->setTitle('Attendance');
            $sheet->fromArray(['Student Number', 'Student Name', 'Course', 'Year', 'Section', 'Check-in', 'Check-out', 'Minutes', 'Completion', 'Status', 'Check-in Method', 'Check-out Method', 'Recorded By'], null, 'A1');
            $number = 2;
            $this->eachRow($event, $filters, function (array $row) use ($sheet, &$number): void {
                $sheet->fromArray(array_map($this->safeCell(...), $this->exportColumns($row)), null, 'A'.$number++);
            });
            $children = $book->createSheet()->setTitle('Sub-Events');
            $children->fromArray(['Activity', 'Eligible', 'Checked In', 'Completed', 'In Progress', 'Incomplete', 'Attendance Rate', 'Completion Rate'], null, 'A1');
            $number = 2;
            foreach ($context['sub_events']['items'] ?? [] as $child) {
                $s = $child['summary'];
                $children->fromArray([$this->safeCell($child['title']), $s['eligible'], $s['checked_in'], $s['completed'], $s['in_progress'], $s['incomplete'], $s['attendance_rate'], $s['completion_rate']], null, 'A'.$number++);
            }
            $participation = $book->createSheet()->setTitle('Participation');
            $participation->fromArray(['Breakdown', 'Label', 'Total'], null, 'A1');
            $number = 2;
            foreach ($context['breakdowns'] as $group => $items) {
                foreach ($items as $item) {
                    $participation->fromArray([$group, $this->safeCell($item->label), $item->total], null, 'A'.$number++);
                }
            }
            (new Xlsx($book))->save('php://output');
            $book->disconnectWorksheets();
        }, $this->filename($event, 'xlsx'), ['Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'Cache-Control' => 'private, no-store']);
    }

    public function pdf(Event $event, array $filters, User $actor): Response
    {
        DB::transaction(fn () => $this->audit->write($event, $actor, 'report.exported', ['format' => 'pdf', 'filters' => $this->safeFilters($filters)]));
        $context = $this->exportContext($event);
        $rows = [];
        $this->eachRow($event, $filters, function (array $row) use (&$rows): void {
            $rows[] = $row;
        });
        $options = new Options;
        $options->set('isRemoteEnabled', false);
        $pdf = new Dompdf($options);
        $pdf->loadHtml(view('events.report-pdf', $context + ['rows' => $rows, 'generated_at' => now(), 'generated_by' => trim(($actor->profile?->first_name ?? '').' '.($actor->profile?->last_name ?? '')) ?: $actor->username])->render());
        $pdf->setPaper('a4', 'landscape');
        $pdf->render();

        return response($pdf->output(), 200, ['Content-Type' => 'application/pdf', 'Content-Disposition' => 'attachment; filename="'.$this->filename($event, 'pdf').'"', 'Cache-Control' => 'private, no-store']);
    }

    public function summary(Event $event): array
    {
        $eligible = $this->audiences->eligibleStudents($event)->count();
        $base = EventAttendance::query()->where('event_id', $event->id);
        $counts = (clone $base)->selectRaw('status, count(*) aggregate')->groupBy('status')->pluck('aggregate', 'status');
        $present = (int) ($counts['present'] ?? 0);
        $late = (int) ($counts['late'] ?? 0);
        $excused = (int) ($counts['excused'] ?? 0);
        $completion = (clone $base)->whereIn('status', ['present', 'late'])->selectRaw('completion_status, count(*) aggregate')->groupBy('completion_status')->pluck('aggregate', 'completion_status');
        $checkedIn = (clone $base)->whereNotNull('checked_in_at')->distinct()->count('student_id');
        $checkedOut = (clone $base)->whereNotNull('checked_out_at')->distinct()->count('student_id');
        $completed = (clone $base)->whereIn('status', ['present', 'late'])->where('completion_status', 'completed')->count();
        $closed = $this->windowClosed($event);
        $absenceFinalized = $closed && $event->status !== 'cancelled';
        $average = (clone $base)->whereNotNull('participation_minutes')->avg('participation_minutes');

        return [
            'eligible' => $eligible, 'checked_in' => $checkedIn, 'checked_out' => $checkedOut, 'present' => $present, 'late' => $late, 'excused' => $excused,
            'absent' => $absenceFinalized ? max(0, $eligible - $checkedIn - $excused) : 0, 'absence_finalized' => $absenceFinalized,
            'completed' => $completed, 'in_progress' => (int) ($completion['in_progress'] ?? 0),
            'incomplete' => (int) ($completion['incomplete'] ?? 0),
            'attendance_rate' => $eligible ? round(($checkedIn / $eligible) * 100, 1) : 0,
            'completion_rate' => $eligible ? round(($completed / $eligible) * 100, 1) : 0,
            'average_participation_minutes' => $average === null ? null : round((float) $average, 1),
        ];
    }

    public function participant(Event $event, Student $student): array
    {
        $attendance = EventAttendance::query()->where('event_id', $event->id)->where('student_id', $student->id)->first();

        return [
            'eligible_participant' => $this->audiences->isStudentEligible($event, $student),
            'completed' => $this->attendanceCompleted($event, $attendance),
            'window_closed' => $this->windowClosed($event),
            'attendance' => $attendance ? ['status' => $attendance->status, 'checked_in_at' => $attendance->checked_in_at?->toIso8601String(), 'checked_out_at' => $attendance->checked_out_at?->toIso8601String(), 'participation_minutes' => $attendance->participation_minutes, 'completion_status' => $attendance->completion_status] : null,
        ];
    }

    public function attendanceCompleted(Event $event, ?EventAttendance $attendance): bool
    {
        if (! $attendance || ! in_array($attendance->status, ['present', 'late'], true) || ! $attendance->checked_in_at) {
            return false;
        }

        return $event->attendance_mode === Event::ATTENDANCE_MODE_CHECK_IN_ONLY
            || ($attendance->checked_out_at !== null && $attendance->completion_status === 'completed');
    }

    private function studentQuery(Event $event, array $filters): Builder
    {
        $eligible = $this->audiences->eligibleStudents($event)->select('students.id');
        $query = Student::query()->select('students.*')->join('user_profiles as report_profiles', 'report_profiles.id', '=', 'students.user_profile_id')
            ->leftJoin('event_attendances as report_attendance', fn ($join) => $join->on('report_attendance.student_id', '=', 'students.id')->where('report_attendance.event_id', $event->id))
            ->where(fn (Builder $students) => $students->whereIn('students.id', $eligible)->orWhereNotNull('report_attendance.id'))
            ->with(['userProfile', 'course:id,course_code', 'enrollments' => fn ($q) => $q->whereIn('status', ['enrolled', 'completed'])->whereHas('academicYear', fn ($year) => $year->where('status', 'active'))->whereHas('semester', fn ($semester) => $semester->where('status', 'active'))->with('section:id,section_name,year_level')]);
        $query->when($filters['search'] ?? null, fn (Builder $q, $value) => $q->where(fn (Builder $student) => $student->where('students.student_number', 'like', "%$value%")->orWhere('report_profiles.first_name', 'like', "%$value%")->orWhere('report_profiles.last_name', 'like', "%$value%")))
            ->when($filters['status'] ?? null, fn (Builder $q, $value) => $value === 'not_recorded' ? $q->whereNull('report_attendance.id') : $q->where('report_attendance.status', $value))
            ->when($filters['course_id'] ?? null, fn (Builder $q, $value) => $q->where(fn (Builder $academic) => $academic->where('report_attendance.course_id_at_attendance', $value)->orWhere(fn (Builder $current) => $current->whereNull('report_attendance.id')->where('students.course_id', $value))))
            ->when($filters['year_level'] ?? null, fn (Builder $q, $value) => $q->where(fn (Builder $academic) => $academic->where('report_attendance.year_level_at_attendance', $value)->orWhere(fn (Builder $current) => $current->whereNull('report_attendance.id')->where(fn (Builder $year) => $year->where('students.year_level', $value)->orWhereHas('enrollments.section', fn (Builder $section) => $section->where('year_level', $value))))))
            ->when($filters['section_id'] ?? null, fn (Builder $q, $value) => $q->where(fn (Builder $academic) => $academic->where('report_attendance.section_id_at_attendance', $value)->orWhere(fn (Builder $current) => $current->whereNull('report_attendance.id')->whereHas('enrollments', fn (Builder $enrollment) => $enrollment->where('section_id', $value)))))
            ->when(($filters['sort'] ?? 'student') === 'check_in', fn (Builder $q) => $q->orderByRaw('report_attendance.checked_in_at is null')->orderBy('report_attendance.checked_in_at'))
            ->when(($filters['sort'] ?? 'student') === 'status', fn (Builder $q) => $q->orderByRaw("coalesce(report_attendance.status, 'not_recorded')"))
            ->orderBy('report_profiles.last_name')->orderBy('report_profiles.first_name')->orderBy('students.id');

        return $query;
    }

    private function row(Student $student, ?EventAttendance $attendance): array
    {
        $enrollment = $student->enrollments->first();
        $hasSnapshot = $attendance && ($attendance->course_id_at_attendance || $attendance->year_level_at_attendance || $attendance->section_id_at_attendance);

        return [
            'student_number' => $student->student_number,
            'name' => trim($student->userProfile->first_name.' '.$student->userProfile->last_name),
            'course' => $attendance ? ($hasSnapshot ? ($attendance->courseAtAttendance?->course_code ?? '—') : 'Historical context unavailable') : ($student->course?->course_code ?? '—'),
            'year_level' => $attendance ? ($hasSnapshot ? ($attendance->year_level_at_attendance ?? '—') : '—') : ($enrollment?->section?->year_level ?? $student->year_level ?? '—'),
            'section' => $attendance ? ($hasSnapshot ? ($attendance->sectionAtAttendance?->section_name ?? '—') : '—') : ($enrollment?->section?->section_name ?? '—'),
            'checked_in_at' => $attendance?->checked_in_at?->toIso8601String(),
            'checked_out_at' => $attendance?->checked_out_at?->toIso8601String(),
            'participation_minutes' => $attendance?->participation_minutes,
            'completion_status' => $attendance?->completion_status ?? 'not_recorded',
            'status' => $attendance?->status ?? 'not_recorded', 'source' => $attendance?->source ?? '—',
            'check_in_method' => $attendance?->check_in_method ?? $attendance?->source ?? '—',
            'check_out_method' => $attendance?->check_out_method ?? '—',
            'recorded_by' => $attendance ? (trim(($attendance->recorder?->profile?->first_name ?? '').' '.($attendance->recorder?->profile?->last_name ?? '')) ?: 'System') : '—',
        ];
    }

    private function eventSummary(Event $event): array
    {
        return $this->eventInformation($event) + ['summary' => $this->summary($event)];
    }

    private function eventInformation(Event $event): array
    {
        $audiences = $event->audiences->isNotEmpty() ? $event->audiences : ($event->parent?->audiences ?? collect());

        return [
            'id' => $event->id, 'parent_event_id' => $event->parent_event_id, 'title' => $event->title,
            'starts_at' => $event->starts_at->toIso8601String(), 'ends_at' => $event->ends_at->toIso8601String(),
            'venue' => $event->venue, 'status' => $event->presentationStatus(), 'attendance_mode' => $event->attendance_mode,
            'minimum_participation_minutes' => $event->minimum_participation_minutes,
            'audience' => $audiences->map(fn ($a) => match ($a->audience_type) {
                'all_students' => 'All Students', 'all_professors' => 'All Professors', 'all_users' => 'All academic users',
                'course' => $a->course?->course_code ?? 'Course', 'year_level' => 'Year '.$a->year_level,
                'section' => $a->section?->section_name ?? 'Section', default => 'Audience',
            })->implode(', ').($event->audiences->isEmpty() && $event->parent ? ' (inherited)' : ''),
        ];
    }

    private function breakdowns(Event $event): array
    {
        $base = EventAttendance::query()->where('event_attendances.event_id', $event->id)->whereIn('event_attendances.status', ['present', 'late', 'excused']);
        $courseLabel = "coalesce(courses.course_code, 'Unavailable')";
        $yearLabel = "coalesce(cast(event_attendances.year_level_at_attendance as char), 'Unavailable')";
        $sectionLabel = "coalesce(sections.section_name, 'Unavailable')";
        $methodLabel = "coalesce(event_attendances.check_in_method, event_attendances.source, 'Unavailable')";
        $dateLabel = 'date(event_attendances.checked_in_at)';
        $course = (clone $base)->leftJoin('courses', 'courses.id', '=', 'event_attendances.course_id_at_attendance')->selectRaw("$courseLabel label, count(*) total")->groupByRaw($courseLabel)->orderBy('label')->get();
        $year = (clone $base)->selectRaw("$yearLabel label, count(*) total")->groupByRaw($yearLabel)->orderBy('label')->get();
        $section = (clone $base)->leftJoin('sections', 'sections.id', '=', 'event_attendances.section_id_at_attendance')->selectRaw("$sectionLabel label, count(*) total")->groupByRaw($sectionLabel)->orderBy('label')->get();
        $method = (clone $base)->selectRaw("$methodLabel label, count(distinct event_attendances.student_id) total")->groupByRaw($methodLabel)->orderBy('label')->get();
        $date = (clone $base)->whereNotNull('event_attendances.checked_in_at')->selectRaw("$dateLabel label, count(distinct event_attendances.student_id) total")->groupByRaw($dateLabel)->orderBy('label')->get();
        $event->loadMissing('attendanceSession');
        $session = $event->attendanceSession ? collect([(object) ['label' => 'Session '.$event->attendanceSession->id.' ('.$event->attendanceSession->status.')', 'total' => (clone $base)->where('attendance_session_id', $event->attendanceSession->id)->distinct()->count('student_id')]]) : collect();

        return compact('course', 'year', 'section', 'method', 'date', 'session');
    }

    private function subEventSummary(Event $event): array
    {
        if ($event->parent_event_id) {
            return [];
        }
        $children = $event->subEvents()->with(['audiences', 'parent.audiences'])->get();
        $items = $children->map(fn (Event $child) => $this->eventInformation($child) + ['summary' => $this->summary($child)])->values();
        $unique = EventAttendance::query()->whereIn('event_id', $children->pluck('id'))->whereNotNull('checked_in_at')->distinct('student_id')->count('student_id');

        return ['items' => $items, 'overall_unique_attendees' => $unique];
    }

    private function safeFilters(array $filters): array
    {
        return collect($filters)->only(['status', 'course_id', 'year_level', 'section_id', 'search', 'sort'])->filter(fn ($value) => $value !== null && $value !== '')->all();
    }

    private function windowClosed(Event $event): bool
    {
        $event->loadMissing('attendanceSession');

        return in_array($event->status, ['cancelled', 'archived'], true)
            || now()->gte($event->ends_at)
            || $event->attendanceSession?->status === 'closed';
    }

    private function safeCell(mixed $value): mixed
    {
        return is_string($value) && preg_match('/^[=+\-@]/', $value) ? "'".$value : $value;
    }

    private function exportColumns(array $row): array
    {
        return [$row['student_number'], $row['name'], $row['course'], $row['year_level'], $row['section'], $row['checked_in_at'], $row['checked_out_at'], $row['participation_minutes'], $row['completion_status'], $row['status'], $row['check_in_method'], $row['check_out_method'], $row['recorded_by']];
    }

    private function eachRow(Event $event, array $filters, callable $callback): void
    {
        $this->studentQuery($event, $filters)->chunkById(500, function ($students) use ($event, $callback): void {
            $records = EventAttendance::query()->where('event_id', $event->id)->whereIn('student_id', $students->pluck('id'))
                ->with(['courseAtAttendance:id,course_code', 'sectionAtAttendance:id,section_name,year_level', 'recorder.profile'])->get()->keyBy('student_id');
            foreach ($students as $student) {
                $callback($this->row($student, $records->get($student->id)));
            }
        }, 'students.id', 'id');
    }

    private function exportContext(Event $event): array
    {
        $event->loadMissing(['audiences.course:id,course_code', 'audiences.section:id,section_name', 'parent.audiences.course:id,course_code', 'parent.audiences.section:id,section_name', 'attendanceSession']);

        return ['event' => $this->eventInformation($event), 'summary' => $this->summary($event), 'breakdowns' => $this->breakdowns($event), 'sub_events' => $this->subEventSummary($event)];
    }

    private function filename(Event $event, string $extension): string
    {
        return Str::slug($event->title).'-attendance-'.$event->starts_at->format('Y-m-d').'.'.$extension;
    }
}
